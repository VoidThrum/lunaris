//! The receiving side of the GameStream audio stream: one UDP datagram in,
//! Opus packets out in order. No sockets, no threads, no clock of its own.
//!
//! Ported from moonlight-common-c (GPLv3): `RtpAudioQueue.c` (FEC blocks of
//! 4 data + 2 parity packets, reordering) and `AudioStream.c`
//! (`decodeInputData`: decryption). The host's side was read in Sunshine
//! `src/stream.cpp` (`audioBroadcastThread`, `encode_audio`) and
//! `src/audio.cpp`, tag v2026.914 and master: no difference on the wire.
//!
//! How the caller drives it:
//!
//! ```text
//! let mut rx = AudioReceiver::new(AudioParams { packet_duration_ms, app_version, encryption })?;
//! loop {
//!     let n = socket.recv(&mut buf);              // buf >= MAX_AUDIO_DATAGRAM
//!     for out in rx.push(&buf[..n], Instant::now()) {
//!         match out {
//!             AudioOut::Packet { data, .. } => one Opus packet to the pipeline,
//!             AudioOut::Lost { .. } => one packet is missing for good (conceal or skip),
//!         }
//!     }
//! }
//! ```
//!
//! - `packet_duration_ms` is `x-nv-aqos.packetDuration` of the ANNOUNCE
//!   (Moonlight sends 5 or 10; Sunshine's default when absent is 5).
//! - `encryption` is `Some` when audio encryption was agreed: bit
//!   `SS_ENC_AUDIO` (0x04) of `x-ss-general.encryptionEnabled`, or bit 0x20
//!   of `x-nv-general.featureFlags` (rtsp.cpp turns that into the same).
//!   Key = `rikey`, and the `rikeyid` of the launch request.
//! - Not ported from `AudioReceiveThreadProc`: dropping the first 500 ms of
//!   audio that piled up on the host before the client listened
//!   (`packetsToDrop`); that belongs to whoever owns the socket and knows
//!   when it went idle.
//!
//! Stereo only. One stereo packet is an ordinary Opus packet (audio.cpp
//! encodes with a multistream encoder of one coupled stream, constant
//! bitrate, so every packet of a stream has the same size, which the FEC
//! needs). A surround stream would need: the stream/coupled-stream counts
//! and the channel mapping from the DESCRIBE answer (`a=fmtp:97
//! surround-params=`), and a consumer for Opus *multistream* packets (several
//! streams in one packet), which neither `Event::Audio` nor WebRTC's Opus
//! carry: it would have to be decoded and encoded again. The queue itself
//! does not care about the channel count.

use std::collections::VecDeque;
use std::time::Instant;

use bytes::Bytes;
use cbc::cipher::block_padding::Pkcs7;
use cbc::cipher::{BlockModeDecrypt, KeyIvInit};

use super::fec::ReedSolomon;
use super::video::{AppVersion, RtpHeader};

// RtpAudioQueue.c / RtpAudioQueue.h
const RTP_PAYLOAD_TYPE_AUDIO: u8 = 97;
const RTP_PAYLOAD_TYPE_FEC: u8 = 127;
pub const RTPA_DATA_SHARDS: usize = 4;
pub const RTPA_FEC_SHARDS: usize = 2;
const RTPA_TOTAL_SHARDS: usize = RTPA_DATA_SHARDS + RTPA_FEC_SHARDS;
/// How long a block is waited for after out-of-order data was seen.
const RTPQ_OOS_WAIT_TIME_MS: u64 = 10;
/// RtpAudioQueue.h: `sizeof(AUDIO_FEC_HEADER)`: fecShardIndex, payloadType,
/// baseSequenceNumber, baseTimestamp, ssrc (big-endian).
const AUDIO_FEC_HEADER_SIZE: usize = 12;
/// AudioStream.c: `MAX_PACKET_SIZE`: the receive buffer of the audio socket.
pub const MAX_AUDIO_DATAGRAM: usize = 1400;

/// The parity matrix both sides put in place of the computed one
/// (RtpAudioQueue.c: `RtpaInitializeQueue`; stream.cpp:
/// `audioBroadcastThread`): "the matrix generated by OpenFEC", which is what
/// Nvidia's audio FEC uses.
pub const AUDIO_PARITY_MATRIX: [u8; 8] = [0x77, 0x40, 0x38, 0x0e, 0xc7, 0xa7, 0x0d, 0x6c];

fn before16(x: u16, y: u16) -> bool {
    x.wrapping_sub(y) > u16::MAX / 2
}

/// Key material of the encrypted audio stream: AES-128-CBC with PKCS#7
/// padding, key = the launch's `rikey`; the IV of a packet is the big-endian
/// 32-bit sum of `rikeyid` and the packet's RTP sequence number, followed by
/// twelve zero bytes (AudioStream.c: `decodeInputData`; stream.cpp:
/// `audioBroadcastThread`).
#[derive(Clone)]
pub struct AudioEncryption {
    pub key: [u8; 16],
    /// The `rikeyid` of the launch request as its 32 bits (the first four
    /// bytes of the launch's input IV read big-endian: AudioStream.c
    /// `avRiKeyId`).
    pub rikeyid: u32,
}

#[derive(Clone)]
pub struct AudioParams {
    /// `x-nv-aqos.packetDuration` in milliseconds.
    pub packet_duration_ms: u32,
    pub app_version: AppVersion,
    pub encryption: Option<AudioEncryption>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AudioOut {
    /// One Opus packet (decrypted), in stream order.
    Packet { sequence_number: u16, rtp_timestamp: u32, data: Bytes },
    /// The packet with this sequence number is lost and will not come: the
    /// consumer conceals it (the reference calls the decoder with no data).
    Lost { sequence_number: u16 },
}

/// Counters for a log line (RtpAudioQueue.h: `RTP_AUDIO_QUEUE_STATS`, and
/// what `decodeInputData` only logs).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct AudioStats {
    pub datagrams: u64,
    pub data_packets: u64,
    pub fec_packets: u64,
    /// Data packets rebuilt from parity.
    pub recovered_packets: u64,
    /// FEC blocks given up incomplete.
    pub unrecoverable_blocks: u64,
    pub out_of_order: u64,
    pub invalid: u64,
    pub fec_invalid: u64,
    pub decrypt_failed: u64,
    /// Opus packets handed out / placeholders for lost ones.
    pub delivered: u64,
    pub lost: u64,
}

/// RtpAudioQueue.h: `RTPA_FEC_BLOCK`.
struct FecBlock {
    payload_type: u8,
    base_sequence_number: u16,
    base_timestamp: u32,
    ssrc: u32,
    /// Payloads of the data packets, then the parity shards; each
    /// `block_size` bytes.
    shards: Vec<Vec<u8>>,
    /// RTP timestamps of the data packets.
    timestamps: [u32; RTPA_DATA_SHARDS],
    /// true = missing
    marks: [bool; RTPA_TOTAL_SHARDS],
    queue_time: Instant,
    data_shards_received: u8,
    fec_shards_received: u8,
    fully_reassembled: bool,
    next_data_packet_index: u8,
    allow_discontinuity: bool,
    block_size: usize,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AudioParamsError {
    PacketDuration,
}

/// RtpAudioQueue.h: `RTP_AUDIO_QUEUE`, with the decryption of AudioStream.c.
pub struct AudioReceiver {
    params: AudioParams,
    rs: ReedSolomon,
    blocks: VecDeque<FecBlock>,
    next_rtp_sequence_number: u16,
    oldest_rtp_base_sequence_number: u16,
    last_oos_sequence_number: u16,
    received_oos_data: bool,
    synchronizing: bool,
    incompatible_server: bool,
    stats: AudioStats,
}

enum Add {
    Rejected,
    HandleNow,
    Queued,
}

impl AudioReceiver {
    /// RtpAudioQueue.c: `RtpaInitializeQueue`; AudioStream.c: `initializeAudioStream`.
    pub fn new(params: AudioParams) -> Result<Self, AudioParamsError> {
        if params.packet_duration_ms == 0 || params.packet_duration_ms > 1000 {
            return Err(AudioParamsError::PacketDuration);
        }
        let rs = ReedSolomon::with_parity_matrix(RTPA_DATA_SHARDS, RTPA_FEC_SHARDS, &AUDIO_PARITY_MATRIX)
            .expect("the audio code's parameters are constants");
        // Hosts before GFE 3.19 break what the FEC code relies on: there the
        // data packets are handed straight on, without FEC and reordering.
        let incompatible_server = !params.app_version.at_least(7, 1, 415);
        Ok(Self {
            params,
            rs,
            blocks: VecDeque::new(),
            next_rtp_sequence_number: 0,
            oldest_rtp_base_sequence_number: 0,
            last_oos_sequence_number: 0,
            received_oos_data: false,
            // Wait for the first whole FEC block before reporting losses.
            synchronizing: true,
            incompatible_server,
            stats: AudioStats::default(),
        })
    }

    pub fn stats(&self) -> AudioStats {
        self.stats
    }

    /// True when the FEC queue was switched off because the host's packets do
    /// not fit it (blocks not starting on a multiple of four, packets of
    /// different sizes within a block): data packets then pass straight
    /// through, in arrival order.
    pub fn fec_disabled(&self) -> bool {
        self.incompatible_server
    }

    /// One UDP datagram of the audio port.
    /// AudioStream.c: `AudioReceiveThreadProc` (after `recvUdpSocket`, without
    /// the initial resync period).
    pub fn push(&mut self, datagram: &[u8], now: Instant) -> Vec<AudioOut> {
        let mut out = Vec::new();
        self.stats.datagrams += 1;
        if datagram.len() > MAX_AUDIO_DATAGRAM {
            self.stats.invalid += 1;
            return out;
        }
        let Some(rtp) = RtpHeader::parse(datagram) else {
            // Runt packet
            self.stats.invalid += 1;
            return out;
        };

        match self.add_packet(&rtp, datagram, now) {
            Add::HandleNow => {
                self.emit(rtp.sequence_number, rtp.timestamp, &datagram[RtpHeader::SIZE..], &mut out);
            }
            Add::Queued => {
                // Pull what is ready
                while self.get_queued_packet(&mut out) {}
            }
            Add::Rejected => {}
        }
        out
    }

    /// AudioStream.c: `decodeInputData`.
    fn emit(&mut self, sequence_number: u16, rtp_timestamp: u32, payload: &[u8], out: &mut Vec<AudioOut>) {
        let data = if let Some(enc) = &self.params.encryption {
            // The IV is the rikeyid plus the RTP sequence number, big-endian.
            let mut iv = [0u8; 16];
            iv[..4].copy_from_slice(&enc.rikeyid.wrapping_add(sequence_number as u32).to_be_bytes());
            let mut buf = payload.to_vec();
            let cipher = cbc::Decryptor::<aes::Aes128>::new(&enc.key.into(), &iv.into());
            match cipher.decrypt_padded::<Pkcs7>(&mut buf) {
                Ok(plain) => {
                    let n = plain.len();
                    buf.truncate(n);
                    buf
                }
                Err(_) => {
                    log::debug!("Sunshine audio: failed to decrypt packet {sequence_number}");
                    self.stats.decrypt_failed += 1;
                    return;
                }
            }
        } else {
            payload.to_vec()
        };
        if data.is_empty() {
            return;
        }
        self.stats.delivered += 1;
        out.push(AudioOut::Packet { sequence_number, rtp_timestamp, data: Bytes::from(data) });
    }

    /// RtpAudioQueue.c: `getFecBlockForRtpPacket`. The index of the block in
    /// `self.blocks` the packet belongs to, if it is to be taken.
    fn fec_block_for_rtp_packet(&mut self, rtp: &RtpHeader, packet: &[u8], now: Instant) -> Option<usize> {
        let length = packet.len();
        let duration = self.params.packet_duration_ms;
        let (payload_type, base_seq, base_ts, ssrc, block_size);

        if rtp.packet_type == RTP_PAYLOAD_TYPE_AUDIO {
            self.stats.data_packets += 1;

            // Out-of-sequence packets seen lately make the queue give up on
            // blocks less quickly.
            if !self.synchronizing && before16(rtp.sequence_number, self.oldest_rtp_base_sequence_number) {
                self.last_oos_sequence_number = rtp.sequence_number;
                self.stats.out_of_order += 1;
                self.received_oos_data = true;
            } else if self.received_oos_data && before16(self.oldest_rtp_base_sequence_number, self.last_oos_sequence_number) {
                // More than 32767 packets without one out of sequence
                self.received_oos_data = false;
            }

            // A data packet: the FEC header is derived
            payload_type = rtp.packet_type;
            base_seq = (rtp.sequence_number / RTPA_DATA_SHARDS as u16) * RTPA_DATA_SHARDS as u16;
            base_ts = rtp.timestamp.wrapping_sub((rtp.sequence_number - base_seq) as u32 * duration);
            ssrc = rtp.ssrc;
            block_size = length - RtpHeader::SIZE;
        } else if rtp.packet_type == RTP_PAYLOAD_TYPE_FEC {
            if length < RtpHeader::SIZE + AUDIO_FEC_HEADER_SIZE {
                self.stats.fec_invalid += 1;
                return None;
            }
            self.stats.fec_packets += 1;

            let h = &packet[RtpHeader::SIZE..];
            let fec_shard_index = h[0];
            payload_type = h[1];
            base_seq = u16::from_be_bytes([h[2], h[3]]);
            base_ts = u32::from_be_bytes([h[4], h[5], h[6], h[7]]);
            ssrc = u32::from_be_bytes([h[8], h[9], h[10], h[11]]);

            if fec_shard_index as usize >= RTPA_FEC_SHARDS {
                self.stats.fec_invalid += 1;
                return None;
            }
            if base_seq % RTPA_DATA_SHARDS as u16 != 0 {
                // Blocks must start on a multiple of four for the queue to
                // work (not so with GeForce Experience 3.13): FEC off.
                self.stats.fec_invalid += 1;
                log::warn!("Sunshine audio: FEC block base sequence number {base_seq} is not a multiple of 4; audio FEC is off");
                self.incompatible_server = true;
                return None;
            }
            block_size = length - RtpHeader::SIZE - AUDIO_FEC_HEADER_SIZE;
        } else {
            self.stats.invalid += 1;
            return None;
        }

        // At the start: begin with the next FEC block boundary, not in the
        // middle of a block.
        if self.synchronizing && self.oldest_rtp_base_sequence_number == 0 {
            self.oldest_rtp_base_sequence_number = base_seq.wrapping_add(RTPA_DATA_SHARDS as u16);
            self.next_rtp_sequence_number = self.oldest_rtp_base_sequence_number;
            return None;
        }

        // Blocks already completed
        if before16(base_seq, self.oldest_rtp_base_sequence_number) {
            return None;
        }

        // An existing block?
        let mut insert_at = self.blocks.len();
        for (i, b) in self.blocks.iter().enumerate() {
            if b.base_sequence_number == base_seq {
                if b.block_size != block_size {
                    // Hosts that do not send packets of one size within a block
                    self.stats.fec_invalid += 1;
                    log::warn!("Sunshine audio: block size mismatch ({block_size}, expected {}); audio FEC is off", b.block_size);
                    self.incompatible_server = true;
                    return None;
                }
                // A completed block takes nothing more
                return if b.fully_reassembled { None } else { Some(i) };
            } else if before16(base_seq, b.base_sequence_number) {
                // The new block goes right before this one
                insert_at = i;
                break;
            }
        }

        let block = FecBlock {
            payload_type,
            base_sequence_number: base_seq,
            base_timestamp: base_ts,
            ssrc,
            shards: vec![vec![0u8; block_size]; RTPA_TOTAL_SHARDS],
            timestamps: [0; RTPA_DATA_SHARDS],
            marks: [true; RTPA_TOTAL_SHARDS],
            queue_time: now,
            data_shards_received: 0,
            fec_shards_received: 0,
            fully_reassembled: false,
            next_data_packet_index: 0,
            allow_discontinuity: false,
            block_size,
        };
        self.blocks.insert(insert_at, block);
        Some(insert_at)
    }

    /// RtpAudioQueue.c: `freeFecBlockHead`
    fn free_fec_block_head(&mut self) {
        if let Some(head) = self.blocks.pop_front() {
            self.oldest_rtp_base_sequence_number = head.base_sequence_number.wrapping_add(RTPA_DATA_SHARDS as u16);
            // Once a block is done (complete or not) the queue is in step
            self.synchronizing = false;
        }
    }

    /// RtpAudioQueue.c: `completeFecBlock`
    fn complete_fec_block(&mut self, index: usize) -> bool {
        let block = &mut self.blocks[index];
        if (block.data_shards_received + block.fec_shards_received) < RTPA_DATA_SHARDS as u8 {
            return false;
        }
        // All data shards: nothing to recover
        if block.data_shards_received as usize == RTPA_DATA_SHARDS {
            return true;
        }
        if block.block_size == 0 || self.rs.decode(&mut block.shards, &block.marks, block.block_size).is_err() {
            return false;
        }
        // The RTP header of a recovered packet comes from the FEC header
        let duration = self.params.packet_duration_ms;
        for i in 0..RTPA_DATA_SHARDS {
            if block.marks[i] {
                block.timestamps[i] = block.base_timestamp.wrapping_add(i as u32 * duration);
                block.marks[i] = false;
            }
        }
        self.stats.recovered_packets += (RTPA_DATA_SHARDS as u8 - block.data_shards_received) as u64;
        true
    }

    /// RtpAudioQueue.c: `queueHasPacketReady`
    fn queue_has_packet_ready(&self) -> bool {
        match self.blocks.front() {
            Some(head) => {
                let idx = head.next_data_packet_index as usize;
                (idx < RTPA_DATA_SHARDS
                    && !head.marks[idx]
                    && head.base_sequence_number.wrapping_add(idx as u16) == self.next_rtp_sequence_number)
                    || head.allow_discontinuity
            }
            None => false,
        }
    }

    /// RtpAudioQueue.c: `handleMissingPackets`
    fn handle_missing_packets(&mut self, now: Instant) {
        let Some(head) = self.blocks.front() else { return };
        let head_base = head.base_sequence_number;

        // The packet waited for precedes the earliest block: a whole block
        // was lost. Go on with the oldest block (without playing it at once
        // with holes: only one of its packets may be here yet).
        if before16(self.next_rtp_sequence_number, head_base) {
            self.next_rtp_sequence_number = head_base;
            self.oldest_rtp_base_sequence_number = head_base;
            return;
        }

        // The next packet is in the first block: it is not given up before a
        // second block is there.
        if self.blocks.len() < 2 {
            return;
        }

        // With a second block queued: no out-of-sequence data seen from this
        // host means the first one is lost; otherwise wait a little longer.
        // (The reference adds the block's duration in milliseconds to a
        // microsecond value; kept as it is: about 10 ms.)
        let wait_us = (self.params.packet_duration_ms as u64 * RTPA_DATA_SHARDS as u64) + RTPQ_OOS_WAIT_TIME_MS * 1000;
        let waited_us = now.saturating_duration_since(head.queue_time).as_micros() as u64;
        if !self.received_oos_data || waited_us > wait_us {
            self.stats.unrecoverable_blocks += 1;
            log::debug!(
                "Sunshine audio: unable to recover block {} to {} ({}+{} received < {} needed)",
                head_base,
                head_base.wrapping_add(RTPA_DATA_SHARDS as u16 - 1),
                head.data_shards_received,
                head.fec_shards_received,
                RTPA_DATA_SHARDS
            );
            // Hand out what is there, with holes
            self.blocks[0].allow_discontinuity = true;
        }
    }

    /// RtpAudioQueue.c: `RtpaAddPacket`
    fn add_packet(&mut self, rtp: &RtpHeader, packet: &[u8], now: Instant) -> Add {
        if self.incompatible_server {
            // Audio data straight through; no handling of reordered or
            // duplicated packets in this mode.
            if rtp.packet_type == RTP_PAYLOAD_TYPE_AUDIO {
                self.stats.data_packets += 1;
                return Add::HandleNow;
            }
            return Add::Rejected;
        }

        let Some(index) = self.fec_block_for_rtp_packet(rtp, packet, now) else {
            return Add::Rejected;
        };

        if rtp.packet_type == RTP_PAYLOAD_TYPE_AUDIO {
            let block = &mut self.blocks[index];
            let pos = rtp.sequence_number.wrapping_sub(block.base_sequence_number) as usize;
            if pos >= RTPA_DATA_SHARDS || !block.marks[pos] {
                // A duplicate
                return Add::Rejected;
            }
            block.shards[pos].copy_from_slice(&packet[RtpHeader::SIZE..]);
            block.timestamps[pos] = rtp.timestamp;
            block.marks[pos] = false;
            block.data_shards_received += 1;

            // The common case: the next data packet in order, handed on at once.
            if rtp.sequence_number == self.next_rtp_sequence_number {
                self.next_rtp_sequence_number = rtp.sequence_number.wrapping_add(1);
                block.next_data_packet_index += 1;
                // All packets of the block handed out: it is done.
                if self.next_rtp_sequence_number == block.base_sequence_number.wrapping_add(RTPA_DATA_SHARDS as u16) {
                    debug_assert_eq!(index, 0);
                    self.free_fec_block_head();
                }
                return Add::HandleNow;
            }
        } else {
            let block = &mut self.blocks[index];
            let fec_shard_index = packet[RtpHeader::SIZE] as usize;
            let slot = RTPA_DATA_SHARDS + fec_shard_index;
            if !block.marks[slot] {
                // A duplicate
                return Add::Rejected;
            }
            block.shards[slot].copy_from_slice(&packet[RtpHeader::SIZE + AUDIO_FEC_HEADER_SIZE..]);
            block.marks[slot] = false;
            block.fec_shards_received += 1;
        }

        // Complete the block from its data shards, or data and parity
        if self.complete_fec_block(index) {
            self.blocks[index].fully_reassembled = true;
        }

        // Nothing ready: should the missing packets be skipped?
        if !self.queue_has_packet_ready() {
            self.handle_missing_packets(now);
        }

        if self.queue_has_packet_ready() {
            Add::Queued
        } else {
            Add::Rejected
        }
    }

    /// RtpAudioQueue.c: `RtpaGetQueuedPacket`. False when nothing is ready.
    fn get_queued_packet(&mut self, out: &mut Vec<AudioOut>) -> bool {
        // Handing out a block with holes: a placeholder for each packet that
        // was lost and could not be recovered.
        if let Some(head) = self.blocks.front_mut() {
            if head.allow_discontinuity {
                let idx = head.next_data_packet_index as usize;
                if idx < RTPA_DATA_SHARDS && head.marks[idx] {
                    let seq = head.base_sequence_number.wrapping_add(idx as u16);
                    head.next_data_packet_index += 1;
                    self.next_rtp_sequence_number = self.next_rtp_sequence_number.wrapping_add(1);
                    if head.next_data_packet_index as usize == RTPA_DATA_SHARDS {
                        self.free_fec_block_head();
                    }
                    self.stats.lost += 1;
                    out.push(AudioOut::Lost { sequence_number: seq });
                    return true;
                }
            }
        }

        if !self.queue_has_packet_ready() {
            return false;
        }
        let Some(head) = self.blocks.front_mut() else { return false };
        let idx = head.next_data_packet_index as usize;
        if idx >= RTPA_DATA_SHARDS {
            self.free_fec_block_head();
            return true;
        }
        let seq = head.base_sequence_number.wrapping_add(idx as u16);
        let ts = head.timestamps[idx];
        // A copy: a block handed out with holes may still be completed by a
        // late packet, which needs every shard in place.
        let payload = head.shards[idx].clone();
        let _ = (head.payload_type, head.ssrc);
        head.next_data_packet_index += 1;
        self.next_rtp_sequence_number = self.next_rtp_sequence_number.wrapping_add(1);
        if head.next_data_packet_index as usize == RTPA_DATA_SHARDS {
            self.free_fec_block_head();
        }
        self.emit(seq, ts, &payload, out);
        true
    }
}

