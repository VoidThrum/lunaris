//! Audio tests, in process: the HOST's side is written here from Sunshine
//! `src/stream.cpp` (`audioBroadcastThread`, `encode_audio`, the audio part
//! of `session::alloc`; v2026.914, the same on master).

use super::*;
use cbc::cipher::{BlockModeEncrypt, KeyIvInit};

struct Lcg(u32);
impl Lcg {
    fn byte(&mut self) -> u8 {
        self.0 = self.0.wrapping_mul(1103515245).wrapping_add(12345);
        (self.0 >> 16) as u8
    }
}

const KEY: [u8; 16] = *b"fedcba9876543210";
const RIKEYID: u32 = 0xFFFF_FFF0; // the sum with the sequence number wraps
const DURATION: u32 = 5;

/// stream.cpp: `session->audio`. (Also the audio sender of `fake_host.rs`.)
pub(crate) struct Host {
    encrypted: bool,
    key: [u8; 16],
    rikeyid: u32,
    sequence_number: u16,
    timestamp: u32,
    shards: Vec<Vec<u8>>,
    fec_base_sequence_number: u16,
    fec_base_timestamp: u32,
    rs: ReedSolomon,
}

impl Host {
    fn new(encrypted: bool) -> Self {
        Self::with_key(encrypted, KEY, RIKEYID)
    }

    /// `key` and `rikeyid`: the launch's (stream.cpp session::alloc
    /// `audio.cipher`, `audio.avRiKeyId`).
    pub(crate) fn with_key(encrypted: bool, key: [u8; 16], rikeyid: u32) -> Self {
        Self {
            encrypted,
            key,
            rikeyid,
            sequence_number: 0,
            timestamp: 0,
            shards: vec![Vec::new(); RTPA_TOTAL_SHARDS],
            fec_base_sequence_number: 0,
            fec_base_timestamp: 0,
            // "we can simply replace it with the matrix generated by OpenFEC"
            rs: ReedSolomon::with_parity_matrix(RTPA_DATA_SHARDS, RTPA_FEC_SHARDS, &AUDIO_PARITY_MATRIX).unwrap(),
        }
    }

    /// One Opus packet in; the datagrams it causes out (the data packet,
    /// and after the fourth of a block the two FEC packets).
    /// stream.cpp: `audioBroadcastThread`, one loop iteration.
    pub(crate) fn send(&mut self, opus: &[u8]) -> Vec<Vec<u8>> {
        let sequence_number = self.sequence_number;
        let timestamp = self.timestamp;

        // encode_audio
        let payload = if self.encrypted {
            let mut iv = [0u8; 16];
            iv[..4].copy_from_slice(&self.rikeyid.wrapping_add(sequence_number as u32).to_be_bytes());
            let mut buf = opus.to_vec();
            buf.resize(opus.len() + 16, 0);
            let n = cbc::Encryptor::<aes::Aes128>::new(&self.key.into(), &iv.into())
                .encrypt_padded::<Pkcs7>(&mut buf, opus.len())
                .unwrap()
                .len();
            buf.truncate(n);
            buf
        } else {
            opus.to_vec()
        };
        let bytes = payload.len();
        self.shards[sequence_number as usize % RTPA_DATA_SHARDS] = payload.clone();

        self.sequence_number = self.sequence_number.wrapping_add(1);
        self.timestamp = self.timestamp.wrapping_add(DURATION);

        let mut out = Vec::new();
        // audio_packet_t: RTP header 0x80, type 97, ssrc 0
        let mut d = vec![0x80, 97];
        d.extend_from_slice(&sequence_number.to_be_bytes());
        d.extend_from_slice(&timestamp.to_be_bytes());
        d.extend_from_slice(&0u32.to_be_bytes());
        d.extend_from_slice(&payload);
        out.push(d);

        if sequence_number as usize % RTPA_DATA_SHARDS == 0 {
            self.fec_base_sequence_number = sequence_number;
            self.fec_base_timestamp = timestamp;
        }
        if (sequence_number as usize + 1) % RTPA_DATA_SHARDS == 0 {
            self.shards[4] = vec![0u8; bytes];
            self.shards[5] = vec![0u8; bytes];
            self.rs.encode(&mut self.shards, bytes).unwrap();
            for x in 0..RTPA_FEC_SHARDS {
                // audio_fec_packet_t: RTP header 0x80, type 127, timestamp 0, ssrc 0
                let mut d = vec![0x80, 127];
                d.extend_from_slice(&sequence_number.wrapping_add(x as u16 + 1).to_be_bytes());
                d.extend_from_slice(&0u32.to_be_bytes());
                d.extend_from_slice(&0u32.to_be_bytes());
                // AUDIO_FEC_HEADER
                d.push(x as u8);
                d.push(97);
                d.extend_from_slice(&self.fec_base_sequence_number.to_be_bytes());
                d.extend_from_slice(&self.fec_base_timestamp.to_be_bytes());
                d.extend_from_slice(&0u32.to_be_bytes());
                d.extend_from_slice(&self.shards[RTPA_DATA_SHARDS + x]);
                out.push(d);
            }
        }
        out
    }

    /// One FEC block: 4 Opus packets (constant size, as the host's encoder
    /// makes them) and its 6 datagrams.
    fn block(&mut self, rng: &mut Lcg, size: usize) -> (Vec<Vec<u8>>, Vec<Vec<u8>>) {
        let mut opus = Vec::new();
        let mut datagrams = Vec::new();
        for _ in 0..RTPA_DATA_SHARDS {
            let mut p: Vec<u8> = (0..size).map(|_| rng.byte()).collect();
            p[0] = 0xFC; // an Opus TOC byte
            datagrams.extend(self.send(&p));
            opus.push(p);
        }
        (opus, datagrams)
    }
}

fn receiver(encrypted: bool) -> AudioReceiver {
    AudioReceiver::new(AudioParams {
        packet_duration_ms: DURATION,
        app_version: AppVersion::SUNSHINE,
        encryption: encrypted.then(|| AudioEncryption { key: KEY, rikeyid: RIKEYID }),
    })
    .unwrap()
}

fn push_all(rx: &mut AudioReceiver, datagrams: &[Vec<u8>]) -> Vec<AudioOut> {
    let now = Instant::now();
    datagrams.iter().flat_map(|d| rx.push(d, now)).collect()
}

fn packet(seq: u16, opus: &[u8]) -> AudioOut {
    AudioOut::Packet { sequence_number: seq, rtp_timestamp: seq as u32 * DURATION, data: Bytes::copy_from_slice(opus) }
}

/// Host and receiver after the first FEC block, which the queue uses to
/// find the block boundary and does not hand out.
fn started(encrypted: bool, rng: &mut Lcg, size: usize) -> (Host, AudioReceiver) {
    let mut host = Host::new(encrypted);
    let mut rx = receiver(encrypted);
    let (_, d) = host.block(rng, size);
    assert!(push_all(&mut rx, &d).is_empty());
    (host, rx)
}

#[test]
fn in_order_stream_round_trips() {
    for encrypted in [false, true] {
        for size in [1usize, 15, 16, 17, 160, 321, 1000] {
            let mut rng = Lcg(size as u32);
            let (mut host, mut rx) = started(encrypted, &mut rng, size);
            let mut expected = Vec::new();
            let mut got = Vec::new();
            for _ in 0..50 {
                let (opus, d) = host.block(&mut rng, size);
                for (i, o) in opus.iter().enumerate() {
                    expected.push(packet(host.sequence_number - 4 + i as u16, o));
                }
                got.extend(push_all(&mut rx, &d));
            }
            assert_eq!(got, expected, "enc {encrypted} size {size}");
            let st = rx.stats();
            assert_eq!(st.delivered, 200);
            assert_eq!(st.recovered_packets + st.lost + st.unrecoverable_blocks + st.decrypt_failed + st.invalid, 0);
            assert!(!rx.fec_disabled());
        }
    }
}

fn without(datagrams: &[Vec<u8>], drop: &[usize]) -> Vec<Vec<u8>> {
    datagrams.iter().enumerate().filter(|(i, _)| !drop.contains(i)).map(|(_, d)| d.clone()).collect()
}

#[test]
fn every_single_and_double_loss_in_a_block_is_recovered() {
    for encrypted in [false, true] {
        let mut drops: Vec<Vec<usize>> = (0..6).map(|i| vec![i]).collect();
        for a in 0..6 {
            for b in a + 1..6 {
                drops.push(vec![a, b]);
            }
        }
        assert_eq!(drops.len(), 21);
        for drop in drops {
            let mut rng = Lcg(7);
            let (mut host, mut rx) = started(encrypted, &mut rng, 200);
            let mut expected = Vec::new();
            let mut got = Vec::new();
            // The same loss in three blocks in a row, then a clean block
            for n in 0..4 {
                let (opus, d) = host.block(&mut rng, 200);
                for (i, o) in opus.iter().enumerate() {
                    expected.push(packet(host.sequence_number - 4 + i as u16, o));
                }
                let d = if n < 3 { without(&d, &drop) } else { d };
                got.extend(push_all(&mut rx, &d));
            }
            assert_eq!(got, expected, "enc {encrypted} drop {drop:?}");
            let lost_data = drop.iter().filter(|&&i| i < 4).count() as u64;
            assert_eq!(rx.stats().recovered_packets, 3 * lost_data, "drop {drop:?}");
            assert_eq!(rx.stats().lost, 0);
        }
    }
}

#[test]
fn three_losses_in_a_block_give_placeholders_and_the_stream_goes_on() {
    for encrypted in [false, true] {
        for a in 0..6usize {
            for b in a + 1..6 {
                for c in b + 1..6 {
                    let drop = [a, b, c];
                    let mut rng = Lcg(11);
                    let (mut host, mut rx) = started(encrypted, &mut rng, 120);
                    let (opus1, d1) = host.block(&mut rng, 120);
                    let (opus2, d2) = host.block(&mut rng, 120);
                    let (opus3, d3) = host.block(&mut rng, 120);
                    let mut got = push_all(&mut rx, &without(&d1, &drop));
                    got.extend(push_all(&mut rx, &d2));
                    got.extend(push_all(&mut rx, &d3));

                    let mut expected = Vec::new();
                    for i in 0..4usize {
                        if drop.contains(&i) {
                            expected.push(AudioOut::Lost { sequence_number: 4 + i as u16 });
                        } else {
                            expected.push(packet(4 + i as u16, &opus1[i]));
                        }
                    }
                    for i in 0..4usize {
                        expected.push(packet(8 + i as u16, &opus2[i]));
                    }
                    for i in 0..4usize {
                        expected.push(packet(12 + i as u16, &opus3[i]));
                    }
                    assert_eq!(got, expected, "enc {encrypted} drop {drop:?}");
                    assert_eq!(rx.stats().unrecoverable_blocks, 1);
                }
            }
        }
    }
}

#[test]
fn a_whole_block_lost_is_skipped() {
    let mut rng = Lcg(12);
    let (mut host, mut rx) = started(true, &mut rng, 80);
    let (_, _lost) = host.block(&mut rng, 80);
    let (opus2, d2) = host.block(&mut rng, 80);
    let (opus3, d3) = host.block(&mut rng, 80);
    let mut got = push_all(&mut rx, &d2);
    got.extend(push_all(&mut rx, &d3));
    let mut expected = Vec::new();
    for i in 0..4usize {
        expected.push(packet(8 + i as u16, &opus2[i]));
    }
    for i in 0..4usize {
        expected.push(packet(12 + i as u16, &opus3[i]));
    }
    assert_eq!(got, expected);
}

#[test]
fn reordering_and_duplicates_within_a_block() {
    for encrypted in [false, true] {
        let orders: [[usize; 6]; 6] =
            [[5, 4, 3, 2, 1, 0], [1, 0, 3, 2, 5, 4], [4, 5, 0, 1, 2, 3], [3, 0, 4, 1, 5, 2], [0, 2, 1, 3, 4, 5], [2, 3, 4, 5, 0, 1]];
        for order in orders {
            let mut rng = Lcg(13);
            let (mut host, mut rx) = started(encrypted, &mut rng, 64);
            let mut expected = Vec::new();
            let mut got = Vec::new();
            for _ in 0..5 {
                let (opus, d) = host.block(&mut rng, 64);
                for (i, o) in opus.iter().enumerate() {
                    expected.push(packet(host.sequence_number - 4 + i as u16, o));
                }
                let mut shuffled: Vec<Vec<u8>> = order.iter().map(|&i| d[i].clone()).collect();
                // every datagram a second time
                shuffled.extend(d.iter().cloned());
                got.extend(push_all(&mut rx, &shuffled));
            }
            assert_eq!(got, expected, "enc {encrypted} order {order:?}");
            assert_eq!(rx.stats().lost, 0);
        }
    }
}

#[test]
fn sequence_number_wraps() {
    for encrypted in [false, true] {
        let mut rng = Lcg(14);
        let mut host = Host::new(encrypted);
        host.sequence_number = 65_496;
        host.timestamp = 65_496 * DURATION;
        let mut rx = receiver(encrypted);
        let (_, d) = host.block(&mut rng, 100);
        assert!(push_all(&mut rx, &d).is_empty());
        for n in 0..30usize {
            let (opus, d) = host.block(&mut rng, 100);
            let first = host.sequence_number.wrapping_sub(4);
            // lose one data packet and one parity packet in every block
            let got = push_all(&mut rx, &without(&d, &[n % 4, 4 + n % 2]));
            let expected: Vec<AudioOut> = (0..4usize)
                .map(|i| AudioOut::Packet {
                    sequence_number: first.wrapping_add(i as u16),
                    rtp_timestamp: (65_500 + n as u32 * 4 + i as u32) * DURATION,
                    data: Bytes::copy_from_slice(&opus[i]),
                })
                .collect();
            assert_eq!(got, expected, "enc {encrypted} block {n}");
        }
        assert_eq!(rx.stats().recovered_packets, 30);
    }
}

#[test]
fn parity_on_the_wire_is_the_nanors_audio_parity() {
    // The host model above against the vector printed by nanors with the
    // replaced matrix (fec_tests.rs: (4, 2, 16, audio)): same data, same parity.
    let mut st = 4u32 * 1000 + 2 + 16;
    let mut next = || {
        st = st.wrapping_mul(1103515245).wrapping_add(12345);
        (st >> 16) as u8
    };
    let mut host = Host::new(false);
    let mut datagrams = Vec::new();
    for _ in 0..4 {
        let p: Vec<u8> = (0..16).map(|_| next()).collect();
        datagrams.extend(host.send(&p));
    }
    let parity: Vec<u8> = [&datagrams[4][24..], &datagrams[5][24..]].concat();
    let hex: String = parity.iter().map(|b| format!("{b:02x}")).collect();
    assert_eq!(hex, "c39db7f79be32358ad0a44c166c7770d9262785291a201a3ca6e470b026e3a37");
}

#[test]
fn wrong_key_and_garbage() {
    let mut rng = Lcg(15);
    let mut host = Host::new(true);
    let mut rx = AudioReceiver::new(AudioParams {
        packet_duration_ms: DURATION,
        app_version: AppVersion::SUNSHINE,
        encryption: Some(AudioEncryption { key: [1; 16], rikeyid: RIKEYID }),
    })
    .unwrap();
    let mut outs = Vec::new();
    for _ in 0..20 {
        let (_, d) = host.block(&mut rng, 100);
        outs.extend(push_all(&mut rx, &d));
    }
    // PKCS#7 padding passes by chance about once in 256 packets at most
    assert!(outs.len() <= 3);
    assert!(rx.stats().decrypt_failed >= 73);

    let now = Instant::now();
    for encrypted in [false, true] {
        let mut rx = receiver(encrypted);
        let mut host = Host::new(encrypted);
        for len in [0usize, 1, 11, 12, 13, 23, 24, 25, 40, 1400, 1401] {
            let junk: Vec<u8> = (0..len).map(|_| rng.byte()).collect();
            rx.push(&junk, now);
            let mut fec = vec![0x80u8, 127];
            fec.resize(len.max(2), 0xFF);
            rx.push(&fec, now);
            let mut audio = vec![0x80u8, 97];
            audio.resize(len.max(2), 0);
            rx.push(&audio, now);
        }
        for _ in 0..200 {
            let (_, mut d) = host.block(&mut rng, 100);
            for p in d.iter_mut() {
                if rng.byte() % 4 == 0 {
                    let at = rng.byte() as usize % 24;
                    p[at] = rng.byte();
                }
                if rng.byte() % 16 == 0 {
                    p.truncate(rng.byte() as usize % p.len());
                }
            }
            push_all(&mut rx, &d);
        }
    }
}

#[test]
fn old_hosts_pass_audio_straight_through() {
    let mut rng = Lcg(16);
    let mut host = Host::new(false);
    let mut rx = AudioReceiver::new(AudioParams { packet_duration_ms: DURATION, app_version: AppVersion([7, 1, 400, 0]), encryption: None }).unwrap();
    assert!(rx.fec_disabled());
    let (opus, d) = host.block(&mut rng, 100);
    let got = push_all(&mut rx, &d);
    let expected: Vec<AudioOut> = (0..4usize).map(|i| packet(i as u16, &opus[i])).collect();
    assert_eq!(got, expected);
}
